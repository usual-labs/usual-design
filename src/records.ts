import { readdir } from 'node:fs/promises';
import { randomUUID } from 'node:crypto';
import { loadManifest, categoryReady } from './config.js';
import { atomicWrite, hash, optionalRead, safePath } from './files.js';
import { runProject, humanResult } from './project.js';
import { activeFinding } from './rules.js';
import type { Category, AuditResult } from './types.js';
import { parseAuditRecord, parseRepairRecord } from './record-validation.js';
const shellQuote = (s: string) => "'" + s.replaceAll("'", "'\"'\"'") + "'";
export const recordsDir = 'docs/usual-design';
function renderAudit(result: AuditResult) {
  return `<!-- Generated by Usual Design. Keep manual notes in a separate file. -->
# Usual Design audit

Snapshot: ${result.snapshot}

\`\`\`text
${humanResult(result)}
\`\`\`

Inactive categories are unchecked by lint. Re-audit before resuming deferred work.
`;
}
export async function saveAudit(root: string, result: AuditResult) {
  const path = `${recordsDir}/audit.json`,
    markdownPath = `${recordsDir}/audit.md`;
  const old = await optionalRead(await safePath(root, path));
  const oldMarkdown = await optionalRead(await safePath(root, markdownPath));
  const previous = old === null ? null : parseAuditRecord(old, path);
  if (oldMarkdown !== null && (previous === null || oldMarkdown !== renderAudit(previous)))
    throw new Error(
      'audit.md contains non-generated changes. Preserve your notes separately before refreshing.',
    );
  await atomicWrite(
    root,
    path,
    JSON.stringify(result, null, 2) + '\n',
    old === null ? null : hash(old),
  );
  await atomicWrite(
    root,
    markdownPath,
    renderAudit(result),
    oldMarkdown === null ? null : hash(oldMarkdown),
  );
  await refreshRepairProgress(root, result);
  return path;
}
export async function createPlan(
  root: string,
  findingIds: string[],
  expectedSnapshot: string,
  configPath = 'usual.design.json',
) {
  const audit = await runProject(root, 'audit', configPath);
  if (audit.errors.length)
    throw new Error('Repair selection requires a successful complete audit.');
  if (audit.snapshot !== expectedSnapshot)
    throw new Error('Source or policy changed; re-audit before approving repairs.');
  if (!findingIds.length) throw new Error('Select at least one finding.');
  const selected = audit.findings.filter((f) => findingIds.includes(f.id));
  if (selected.some((f) => f.kind === 'decision'))
    throw new Error(
      'Policy decisions require explicit manifest review, not an ordinary application repair batch.',
    );
  if (selected.length !== new Set(findingIds).size)
    throw new Error('Some findings are stale or missing; re-audit.');
  await saveAudit(root, audit);
  const id = randomUUID();
  const path = `${recordsDir}/repairs/${id}.json`;
  const plan = {
    version: 1,
    id,
    status: 'approved',
    snapshot: audit.snapshot,
    manifestHash: audit.manifestHash,
    policyHash: audit.policyHash,
    configPath,
    selected,
    deferred: audit.findings.filter((f) => !findingIds.includes(f.id)),
    constraints: [
      'Repair only selected application findings.',
      'Do not change manifest, rules, exclusions, exceptions, or activation.',
      'Re-audit if source or policy changed before work starts.',
      'Never treat line numbers as authority to edit changed code.',
    ],
    verifyArgv: ['usual-design', 'audit', '--config', configPath],
    verify: `usual-design audit --config ${shellQuote(configPath)}`,
    startArgv: ['usual-design', 'verify-plan', '--plan', path, '--config', configPath],
  };
  await atomicWrite(root, path, JSON.stringify(plan, null, 2) + '\n', null);
  const md = `# Approved repair batch ${id}\n\nSnapshot: ${audit.snapshot}\n\n## Constraints\n\n${plan.constraints.map((x) => `- ${x}`).join('\n')}\n\n## Selected\n\n${selected.map((f) => `- [ ] ${f.file}:${f.line} — ${f.message}`).join('\n')}\n\n## Deferred\n\n${plan.deferred.map((f) => `- ${f.file}:${f.line} — ${f.message}`).join('\n') || 'None'}\n\nRun \`${plan.verify}\` after repairs. Selection is not proof of completion.\n`;
  await atomicWrite(root, path.replace(/json$/, 'md'), md, null);
  await refreshRepairProgress(root, audit);
  return {
    path,
    plan,
    prompt: `Read ${path}. Before editing run usual-design verify-plan --plan ${shellQuote(path)} --config ${shellQuote(configPath)}. Only if it succeeds, execute its approved repair batch. Preserve the manifest and unrelated work. Run the audit afterward and report remaining findings.`,
  };
}

/** Validate saved authority immediately before editing; never execute commands from a record. */
export async function verifyPlan(root: string, path: string, configPath = 'usual.design.json') {
  const absolute = await safePath(root, path);
  const raw = await optionalRead(absolute);
  if (raw === null) throw new Error(`Repair record does not exist: ${path}`);
  const plan = parseRepairRecord(raw, path);
  if (plan.configPath && plan.configPath !== configPath)
    throw new Error('Repair plan uses another manifest path; pass its exact --config value.');
  const audit = await runProject(root, 'audit', configPath);
  if (audit.errors.length) throw new Error('Cannot verify a plan against an incomplete audit.');
  if (plan.snapshot !== audit.snapshot || plan.manifestHash !== audit.manifestHash)
    throw new Error(
      'Stale repair plan: source or policy changed. Re-audit and approve a current batch.',
    );
  if (plan.selected.some((f) => !audit.findings.some((current) => current.id === f.id)))
    throw new Error('Selected findings are no longer current. Re-audit and approve a new batch.');
  if ((await optionalRead(absolute)) !== raw)
    throw new Error('Repair record changed during verification. Reload and review the batch.');
  return {
    valid: true,
    path,
    snapshot: audit.snapshot,
    recordHash: hash(raw),
    selected: plan.selected.length,
  };
}
export async function activate(
  root: string,
  requested: Category[],
  expectedSnapshot?: string,
  configPath = 'usual.design.json',
) {
  const audit = await runProject(root, 'audit', configPath);
  if (expectedSnapshot && audit.snapshot !== expectedSnapshot)
    throw new Error('Stale audit; source or policy changed. Recheck before activation.');
  if (audit.errors.length) throw new Error(`Cannot activate: ${audit.errors.join('; ')}`);
  const { manifest, manifestHash } = await loadManifest(root, configPath);
  if (requested.some((c) => !categoryReady(manifest, c)))
    throw new Error('Each activated category needs an explicit effective policy.');
  const blockers = audit.findings.filter((f) => activeFinding(f, requested));
  if (blockers.length)
    throw new Error(
      `Activation blocked by ${blockers.length} findings: ${blockers
        .slice(0, 3)
        .map((f) => f.message)
        .join('; ')}`,
    );
  const fresh = await runProject(root, 'audit', configPath);
  if (fresh.snapshot !== audit.snapshot)
    throw new Error('Source changed during activation; re-audit.');
  const next =
    JSON.stringify(
      { ...manifest, active: [...new Set([...manifest.active, ...requested])] },
      null,
      2,
    ) + '\n';
  // Prepare a durable decision before committing policy. A receipt alone is not proof of activation.
  await atomicWrite(
    root,
    `${recordsDir}/activation-${randomUUID()}.json`,
    JSON.stringify(
      {
        version: 1,
        status: 'prepared-decision',
        categories: requested,
        previousManifestHash: manifestHash,
        resultingManifestHash: hash(next),
        validatedSnapshot: audit.snapshot,
        verification:
          'Compare resultingManifestHash with the current manifest; this decision may precede a failed commit.',
      },
      null,
      2,
    ) + '\n',
    null,
  );
  const finalAudit = await runProject(root, 'audit', configPath);
  if (finalAudit.snapshot !== audit.snapshot)
    throw new Error('Source changed while preparing activation; re-audit.');
  await atomicWrite(root, configPath, next, manifestHash);
  return runProject(root, 'check', configPath);
}

/** A fresh audit supplies evidence; never infer repair success from a disappearing line number. */
export async function refreshRepairProgress(root: string, audit: AuditResult) {
  const dir = await safePath(root, `${recordsDir}/repairs`);
  let names: string[];
  try {
    names = await readdir(dir);
  } catch (e) {
    if ((e as NodeJS.ErrnoException).code === 'ENOENT') return;
    throw e;
  }
  const signature = (f: import('./types.js').Finding) =>
    JSON.stringify([f.file, f.ruleId, f.actual ?? null, f.expected ?? null, f.message]);
  const current = new Set(audit.findings.map(signature));
  const batches = [];
  for (const name of names.filter((n) => /^[a-f0-9-]+\.json$/.test(n)).sort()) {
    const raw = await optionalRead(await safePath(root, `${recordsDir}/repairs/${name}`));
    if (!raw) continue;
    const plan = parseRepairRecord(raw, `${recordsDir}/repairs/${name}`);
    const policyChanged = plan.policyHash
      ? plan.policyHash !== audit.policyHash
      : plan.manifestHash !== audit.manifestHash;
    const findings = plan.selected.map((f: import('./types.js').Finding) => ({
      id: f.id,
      file: f.file,
      ruleId: f.ruleId,
      status: audit.errors.length
        ? 'audit-incomplete'
        : policyChanged
          ? 'policy-changed-review'
          : !audit.files.includes(f.file)
            ? 'outside-current-coverage'
            : current.has(signature(f))
              ? 'still-reported'
              : 'not-observed-in-current-audit',
    }));
    batches.push({ path: `${recordsDir}/repairs/${name}`, policyChanged, findings });
  }
  const progress = { version: 1, snapshot: audit.snapshot, batches };
  const renderProgress = (value: typeof progress) => {
    if (value.version !== 1 || typeof value.snapshot !== 'string')
      throw new Error('Unsupported or corrupt repair progress record.');
    const lines = value.batches.flatMap((b) => [
      `## ${b.path}`,
      ...b.findings.map(
        (f: { file: string; ruleId: string; status: string }) =>
          `- ${f.file} [${f.ruleId}]: ${f.status}`,
      ),
      '',
    ]);
    return (
      '# Repair verification evidence\n\nFresh audit snapshot: ' +
      value.snapshot +
      '\n\nNot observed is evidence within current coverage, not proof of visual correctness. Moved findings stay reported; policy changes require review. Original approval records remain unchanged.\n\n' +
      lines.join('\n') +
      '\n'
    );
  };
  const jsonPath = `${recordsDir}/repair-progress.json`,
    markdownPath = `${recordsDir}/repair-progress.md`;
  const previous = await optionalRead(await safePath(root, jsonPath)),
    previousMarkdown = await optionalRead(await safePath(root, markdownPath));
  if (previousMarkdown !== null) {
    let generated: string;
    try {
      if (previous === null) throw new Error('Missing repair progress JSON.');
      generated = renderProgress(JSON.parse(previous));
    } catch {
      throw new Error(
        'Repair progress records are incompatible or corrupt. Preserve the originals and restore valid generated records before refreshing.',
      );
    }
    if (previousMarkdown !== generated)
      throw new Error(
        'repair-progress.md contains manual changes. Preserve your notes separately before refreshing.',
      );
  }
  await atomicWrite(
    root,
    jsonPath,
    JSON.stringify(progress, null, 2) + '\n',
    previous === null ? null : hash(previous),
  );
  await atomicWrite(
    root,
    markdownPath,
    renderProgress(progress),
    previousMarkdown === null ? null : hash(previousMarkdown),
  );
}
